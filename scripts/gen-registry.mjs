// 从 VAPT 工具清单生成「通用适配器」条目。
// 用法：node scripts/gen-registry.mjs "<inventory.md>" > src/pentest/registry.generated.js
// 通用适配器 = 命令行可直接跑、参数由模型给（仍受 argAllowed 的禁用开关约束）。
import { readFileSync } from 'node:fs';

const src = process.argv[2];
const md = readFileSync(src, 'utf8');

// GUI / SaaS / 库，不适合当命令行适配器
const SKIP = new Set([
  'burp suite pro', 'owasp zap', 'tenable nessus', 'mobsf', 'sonarqube', 'firecrawl',
  'steampipe', 'tor', 'scapy', 'ldap3', 'inql', 'photon', 'cloud_enum_x', 'shodan_',
]);
// 名字 → 真实二进制名
const BIN = {
  'ffuf': 'ffuf', 'jwt tool': 'jwt_tool', 'netexec (nxc)': 'nxc', 'theharvester': 'theHarvester',
  'searchsploit': 'searchsploit', 'testssl.sh': 'testssl.sh', 'kube-bench': 'kube-bench',
  'kube-hunter': 'kube-hunter', 'youtube-dl': 'yt-dlp', 'metasploit': 'msfconsole',
  'enum4linux-ng': 'enum4linux-ng', 'bloodhound': 'bloodhound-python', 'impacket': 'impacket-GetUserSPNs',
  'responder': 'Responder.py', 'gobuster': 'gobuster', 'waybackpack': 'waybackpack',
  'osrframework': 'osrframework', 'ldapdomaindump': 'ldapdomaindump', 'h8mail': 'h8mail',
};
const CAT = {
  'Reconnaissance': 'recon', 'Discovery': 'web', 'Vulnerability Scanning': 'vuln',
  'Injection & Specialised': 'vuln', 'Network & AD': 'ad', 'Cloud & Container Security': 'cloud',
  'OSINT & Recon': 'osint', 'Mobile Security': 'mobile', 'Load & Performance': 'load',
  'Code & SAST': 'sast', 'Wordlists': 'wordlist',
};

const out = [];
let phase = null;
for (const raw of md.split('\n')) {
  const line = raw.trim();
  const h = /^###\s+(.+)$/.exec(line);
  if (h) { phase = h[1].trim(); continue; }
  if (!phase || /^##\s/.test(line)) { if (/^##\s/.test(line)) phase = null; continue; }
  const row = /^\|\s*([^|]+?)\s*\|\s*(https?:\/\/[^|]+?)\s*\|/.exec(line);
  if (!row) continue;
  const name = row[1];
  if (/^tool$/i.test(name) || /^---/.test(name)) continue;
  const key = name.toLowerCase();
  if (SKIP.has(key)) continue;
  const bin = BIN[key] || key.replace(/\s*\(.*?\)\s*/g, '').replace(/\s+/g, '-');
  const cat = CAT[phase] || 'other';
  const id = bin.replace(/[^a-z0-9._-]/gi, '-').toLowerCase();
  out.push({ id, bin, cat, name, site: row[2] });
}

const seen = new Set();
const entries = out.filter((e) => (seen.has(e.bin) ? false : seen.add(e.bin)));

const lines = entries.map((e) => `  { id: ${JSON.stringify(e.id)}, bin: ${JSON.stringify(e.bin)}, cat: ${JSON.stringify(e.cat)}, generic: true, requires: ['args'], parser: 'text', desc: { zh: ${JSON.stringify(`${e.name}（通用适配器）`)}, en: ${JSON.stringify(`${e.name} (generic adapter)`) } }, site: ${JSON.stringify(e.site)}, mk: (t, o, extra) => [...extra, ...(t ? [t] : [])] },`);

process.stdout.write(`// AUTO-GENERATED by scripts/gen-registry.mjs — 不要手改；改生成器或手写 registry.js。\n// 来源：VAPT-Tool-Inventory.md（用户本地清单）\nexport const GENERATED = [\n${lines.join('\n')}\n];\n`);
console.error(`generated ${entries.length} generic entries`);
